"""Architecture grounding audit: real contamination is caught, ordinary project prose is not (Handbook 14.1.3)."""

import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine"))

import judge

PRD = "# PRD\nStaff keep a private to-do list. Users sign in with email and password. [Q-001]\n"
QA = {"Q-001": {"question": "What is it?", "answer": "A to-do app with sign in, on one offline office computer."}}
ARCH = """## 3. Tech stack
| Layer | Choice |
|---|---|
| Backend | Python standard library http.server [ADR-001] |
The **RBAC Table** below lists who can read todos. Sessions are stored in SQLite with WAL [ADR-002].
The safest stdlib option keeps deps pip installable, bytes approx 2 KB per todo [Q-01].
"""


class ArchitectureGroundingTest(unittest.TestCase):
    def audit(self, text):
        found, _ = judge.run_architecture_code_audits(text, PRD, {"qa_map": QA}, "CREATE TABLE todos (id INTEGER);")
        return [f for f in found if "contamination" in f.get("reason", "") or "Placeholder" in f.get("reason", "")
                or "Cited question" in f.get("reason", "")]

    def test_ordinary_project_prose_is_not_flagged(self):
        self.assertEqual(self.audit(ARCH), [])

    def test_planted_contamination_and_invented_citation_are_caught(self):
        found = self.audit(ARCH + "\n**Airframe Registry** stores Drone Photogrammetry tiles [Q-07].\nTODO: fill in\n")
        texts = {f["text"] for f in found}
        self.assertIn("Airframe Registry", texts)
        self.assertIn("drone photogrammetry", texts)
        self.assertIn("[Q-07]", texts)
        self.assertTrue(any("Placeholder" in f["reason"] for f in found))


    def test_stack_choices_and_lists_are_not_contamination(self):
        # From a real run: a tech-stack table listing alternatives, and diagram node labels.
        stack = ARCH + """| **Web framework** | FastAPI UNVERIFIED:0.110.0 | Flask, Django, Bottle | [ADR-001] |
| **Templating (frontend)** | Jinja2 | Mako | [ADR-001] |
| **Static assets** | Plain CSS | Bootstrap, Bulma | [ADR-001] |
| **CI / Automation** | GitHub Actions | Local make scripts | [ADR-004] |
    TestSuite[PyTest suite] --> QA
"""
        self.assertEqual([f["text"] for f in self.audit(stack)], [])

    def test_invented_requirement_ids_are_caught(self):
        prd = PRD + "| F-001 | Sign in | ... | Must | [FR-001] |\n[NFR-01] fast\n"
        arch = ARCH + "Covers [F-001] and [NFR-01]; also [NFR-09] uptime and [F-042] export.\n"
        found, _ = judge.run_architecture_code_audits(arch, prd, {"qa_map": QA}, "CREATE TABLE todos (id INTEGER);")
        invented = sorted(f["text"] for f in found if "invented id" in f["reason"])
        self.assertEqual(invented, ["[F-042]", "[NFR-09]"])


    def test_ordinary_bold_labels_and_code_names_are_not_contamination(self):
        # From the second real run: every one of these was flagged as cross-project contamination.
        labels = ARCH + ("Each row is about **200 bytes**. **Data durability** relies on WAL. **Frequency:** daily.\n"
                         "Server: **`wsgiref.simple_server`**, hashing **`hashlib.pbkdf2_hmac`**.\n"
                         "**Monolithic MVC\u2011style web application** with **SQLite (std\u2011lib `sqlite3`)** and "
                         "**Static HTML + vanilla JS**.\n")
        self.assertEqual([f["text"] for f in self.audit(labels)], [])

    def test_judge_reads_the_whole_adr_not_an_empty_file(self):
        import tempfile, shutil
        tmp = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(tmp, "adr"))
            with open(os.path.join(tmp, "adr", "ADR-001.md"), "w") as f:
                f.write("<!-- ARTIFACT METADATA: x -->\n> **Artifact Provenance**: Generated by LLM\n\n"
                        "# ADR-001: Web framework\n## Options\nA: stdlib. B: Flask.\n## Decision\nUse stdlib.\n")
            ctx = judge.adr_context_for_judge(tmp)
        finally:
            shutil.rmtree(tmp)
        self.assertIn("# ADR-001: Web framework", ctx)
        self.assertIn("Use stdlib.", ctx)
        self.assertNotIn("Artifact Provenance", ctx)


if __name__ == "__main__":
    unittest.main()
