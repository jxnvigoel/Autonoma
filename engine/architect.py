def generate_feasibility_note(
    session_id: str,
    parsed_ba: Dict[str, Any],
    prd_data: Dict[str, Any],
    docs_dir: str
) -> Dict[str, Any]:
    """
    Produces the Stage 2 Step 8 quick feasibility check (<= 1 page note) via LLM.
    Evaluates scope vs timeline, build budget, technical constraints, and risk mitigations.
    Saves to docs/feasibility.md.
    """
    app_name = prd_data.get("app_name", parsed_ba.get("app_name", "Untitled Project"))
    timeline = parsed_ba.get("timeline", "8 weeks")
    budget = parsed_ba.get("budget", "$5,000 MVP build budget")
    features = prd_data.get("features", [])
    must_features = [f for f in features if "must" in f.get("priority", "").lower()]
    nfrs = prd_data.get("nfrs", [])

    features_summary = "\n".join([f"- **{f['id']}**: {f.get('title') or f.get('name', 'Feature')} ({f.get('priority', 'Must')})" for f in must_features])
    nfrs_summary = "\n".join([f"- **{n.get('id', 'NFR')}**: {n.get('name', '')} - {n.get('target', '')}" for n in nfrs])

    prompt = f"""You are the Lead Solution Architect. Write the quick feasibility check note (<= 1 page, under 500 words) for '{app_name}' adhering to Handbook Section 2.7.3 Step 8.
PROJECT: {app_name}
TARGET TIMELINE: {timeline} [G-01]
TARGET BUDGET: {budget} [Scope Constraints]
CORE MUST FEATURES ({len(must_features)} items):
{features_summary}
CONSTRAINTS (NFRs):
{nfrs_summary}

Structure:
# Feasibility Assessment Note: {app_name}
## 1. Executive Summary & Verdict
(State: **Verdict: FEASIBLE FOR V1 MVP** and summarize fit within timeline and budget)
## 2. Scope vs. Timeline Feasibility (Handbook 7.1.3 & 7.2.4)
(Evaluate {len(must_features)} Must-have features vs {timeline} and de-scoping safeguards [NG-01])
## 3. Budget & Infrastructure Cost Feasibility
(Evaluate $0.00/month local desktop execution vs build budget)
## 4. Technical Constraints & Architecture Mechanisms
(Address query latency, offline execution, and data integrity)
## 5. Architectural Recommendations for Gate 1 Sign-Off
(Concrete recommendations before client approval)

Length: Maximum 1 page (under 500 words). Return ONLY markdown."""

    raw_text, meta = query_llm_with_meta(
        prompt=prompt,
        role="architect",
        session_id=session_id,
        task_id="feasibility_check"
    )

    clean_text = raw_text.strip()
    stamp = _generate_stamp(meta, role_name="Solution Architect")
    final_note = f"{stamp}{clean_text}" if not clean_text.startswith("<!-- ARTIFACT METADATA:") else clean_text

    feasibility_path = os.path.join(docs_dir, "feasibility.md")
    with open(feasibility_path, "w", encoding="utf-8") as f:
        f.write(final_note)

    return {
        "status": "feasible",
        "verdict": "FEASIBLE FOR V1 MVP",
        "path": feasibility_path,
        "content": final_note,
        "meta": meta
    }


