@architect_router.post("/architect/start")
def start_architect_endpoint(req: ArchitectSessionRequest):
    """
    Stage 3 Step 11: Real LLM Architect generates architecture.md, ADRs, openapi.yaml,
    schema.md, and team-plan.json. Validated by code before Tech Lead and Judge review.
    """
    session_id = req.session_id
    from main import get_session_dir, load_json, save_json
    from judge import evaluate_architecture_with_judge

    session_dir = get_session_dir(session_id)
    docs_dir = os.path.join(session_dir, "docs")
    adr_dir = os.path.join(docs_dir, "adr")
    os.makedirs(docs_dir, exist_ok=True)
    os.makedirs(adr_dir, exist_ok=True)

    prd_path = os.path.join(docs_dir, "prd.md")
    intake_path = os.path.join(session_dir, "intake.json")
    qa_path = os.path.join(session_dir, "qa_log.json")
    state_file = os.path.join(session_dir, "session_state.json")

    state = load_json(state_file, {})
    if not state.get("gate1_approved", False):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Cannot start Solution Architect: Gate 1 client approval is required before Stage 3 design."
        )

    with open(prd_path, "r", encoding="utf-8") as f:
        prd_text = f.read()

    prd_data = parse_prd_data(prd_text)
    intake_data = load_json(intake_path, {})
    qa_log = load_json(qa_path, [])
    parsed_ba = parse_ba_data(intake_data, qa_log, prd_text, session_id=session_id)

    # Stage 3 Step 11: LLM generates ADRs, Schema, OpenAPI, Team plan, Architecture TRD
    adrs = generate_adrs(parsed_ba, prd_data, adr_dir, session_id=session_id)
    schema_path = generate_schema_doc(parsed_ba, prd_data, docs_dir, session_id=session_id)
    openapi_path = generate_openapi_spec(parsed_ba, prd_data, docs_dir, session_id=session_id)
    team_plan_path = generate_team_plan(parsed_ba, prd_data, docs_dir, adrs=adrs)
    arch_path = generate_architecture_trd(parsed_ba, prd_data, docs_dir, adr_list=adrs, session_id=session_id)

    with open(arch_path, "r", encoding="utf-8") as f:
        arch_text = f.read()
    with open(schema_path, "r", encoding="utf-8") as f:
        schema_text = f.read()

    # Stage 3 Step 13: Judge evaluation
    judge_verdict = evaluate_architecture_with_judge(
        arch_text=arch_text,
        prd_text=prd_text,
        parsed_ba=parsed_ba,
        rubric_path="skills/architect/rubric.json",
        session_id=session_id,
        schema_text=schema_text
    )

    architect_state = {
        "session_id": session_id,
        "status": "done" if judge_verdict.get("pass", False) else "review_failed",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "artifacts": {
            "architecture": "docs/architecture.md",
            "openapi": "docs/openapi.yaml",
            "schema": "docs/schema.md",
            "team_plan": "docs/team-plan.json",
            "adrs": [a["path"] for a in adrs]
        },
        "judge_verdict": judge_verdict
    }
    save_json(os.path.join(session_dir, "architect_state.json"), architect_state)

    return {
        "session_id": session_id,
        "status": architect_state["status"],
        "artifacts": architect_state["artifacts"],
        "judge_verdict": judge_verdict
    }


