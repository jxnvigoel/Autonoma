def generate_schema_doc(
    parsed_ba: Dict[str, Any],
    prd_data: Dict[str, Any],
    docs_dir: str,
    session_id: Optional[str] = None
) -> str:
    """
    Generates docs/schema.md via LLM adhering to Appendix A.6.
    Code validates the SQL DDL by executing it directly in an in-memory SQLite database.
    Retries up to 3 times feeding back SQLite syntax/constraint errors.
    """
    app_name = prd_data.get("app_name", "App")
    features = prd_data.get("features", [])
    entities = parsed_ba.get("extracted_raw", {}).get("entities", [])
    features_summary = "\n".join([f"- **{f['id']}**: {f.get('title') or f.get('name', '')}" for f in features])

    base_prompt = f"""You are the Lead Solution Architect. Generate docs/schema.md for '{app_name}' adhering to Appendix A.6.
PROJECT: {app_name}
FEATURES REQUIRING DATA PERSISTENCE:
{features_summary}

CRITICAL RULES:
1. Generate real, executable SQLite DDL tables (TBL-01, TBL-02...) for THIS project's actual operational entities.
2. Every table must have real columns, UUID/TEXT primary keys, appropriate foreign keys, CHECK constraints for enums, and timestamps.
3. Include B-tree indexes for all primary query paths.
4. Enclose ALL executable SQL in a single ```sql ... ``` block so it parses and executes in SQLite.

Appendix A.6 Structure:
# Data Schema: {app_name}
**Database**: SQLite 3 (WAL mode) [ADR-002]  
**Query layer**: SQL / Typed Prepared Statements [ADR-002]  
**Migrations**: Embedded schema bootstrap  

## Tables
(Document TBL-01.. with column tables and access rules)

## SQL DDL
```sql
CREATE TABLE IF NOT EXISTS ...
```

## Indexes
| Index | Serves |
|---|---|

## Access rules
| Table | Read | Insert | Update | Delete | Enforced by |
|---|---|---|---|---|---|

## Growth and retention
| Table | Rows year 1 | Retention | Source |
|---|---|---|---|

Return ONLY markdown."""

    current_prompt = base_prompt
    max_attempts = 3
    last_errors = []

    for attempt in range(1, max_attempts + 1):
        logger.info(f"Generating schema.md via LLM (attempt {attempt}/{max_attempts})...")
        raw_text, meta = query_llm_with_meta(
            prompt=current_prompt,
            role="architect",
            session_id=session_id,
            task_id="architect_schema",
            max_tokens=4000,  # one DDL document with foreign keys; 1,500 was cut off mid-table
            reasoning_effort="low"
        )

        is_valid, errors, tables = validate_schema_ddl(raw_text)
        if is_valid:
            logger.info(f"Schema DDL passed SQLite execution check on attempt {attempt} (created tables: {tables}).")
            stamp = _generate_stamp(meta, role_name="Solution Architect")
            clean_text = raw_text.strip()
            final_schema = f"{stamp}{clean_text}" if not clean_text.startswith("<!-- ARTIFACT METADATA:") else clean_text

            schema_path = os.path.join(docs_dir, "schema.md")
            with open(schema_path, "w", encoding="utf-8") as f:
                f.write(final_schema)
            return schema_path

        logger.warning(f"Schema DDL validation failed on attempt {attempt}: {errors}")
        last_errors = errors
        current_prompt = (
            f"{base_prompt}\n\n"
            f"ERROR ON PREVIOUS ATTEMPT {attempt}:\n"
            f"SQLite DDL execution failed with errors:\n"
            + "\n".join(f"- {e}" for e in errors)
            + "\n\nPlease fix the SQL syntax/table constraints so it executes cleanly in sqlite3."
        )

    raise ValueError(f"Schema generation failed SQLite validation after {max_attempts} attempts: {last_errors}")


