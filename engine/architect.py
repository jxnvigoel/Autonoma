@architect_router.post("/gate1/request-changes")
def request_changes_gate1_endpoint(req: Gate1ChangeRequest):
    """
    Stage 2 Step 10: the client sends the PRD back before approving Gate 1.

    The feedback is recorded as a new discovery answer (a Q- entry the PRD can cite), the current PRD is
    kept as a numbered version, and the PM rebuilds the PRD from the updated discovery as a background
    job; the Judge reviews the new version as usual.
    """
    session_id = req.session_id
    from main import get_session_dir, load_json, save_json
    try:
        import jobs as office_jobs
    except ImportError:
        from engine import jobs as office_jobs

    feedback = (req.feedback or "").strip()
    if not feedback:
        raise HTTPException(status_code=400, detail="Say what should change in the PRD.")
    session_dir = get_session_dir(session_id)
    docs_dir = os.path.join(session_dir, "docs")
    state_file = os.path.join(session_dir, "session_state.json")
    state = load_json(state_file, {})
    if state.get("gate1_approved"):
        raise HTTPException(status_code=409, detail="Gate 1 is already approved; the PRD is locked for this release.")
    if office_jobs.status(session_id, "pm", include_result=False).get("status") == "running":
        raise HTTPException(status_code=409, detail="The PM is already writing the PRD; wait for it to finish.")

    now_iso = datetime.now(timezone.utc).isoformat()
    qa_file = os.path.join(session_dir, "qa_log.json")
    qa_log = load_json(qa_file, [])
    nums = [int(m.group(1)) for q in qa_log for m in [re.match(r"Q-(\d+)$", str(q.get("id", "")))] if m]
    qid = f"Q-{(max(nums) if nums else 0) + 1:03d}"
    qa_log.append({"id": qid, "question": "Gate 1 review: what should change in the PRD?", "answer": feedback,
                   "round": max([int(q.get("round") or 0) for q in qa_log] + [0]) + 1,
                   "timestamp": now_iso, "source": "gate1"})
    save_json(qa_file, qa_log)

    # Keep the version the client reviewed, then let the PM rebuild from the updated discovery.
    version = 1
    while os.path.exists(os.path.join(docs_dir, f"prd.v{version}.md")):
        version += 1
    for name, folder in (("prd.md", docs_dir), ("estimate.json", docs_dir), ("pm_state.json", session_dir)):
        src = os.path.join(folder, name)
        if os.path.exists(src):
            stem, ext = os.path.splitext(name)
            os.replace(src, os.path.join(folder, f"{stem}.v{version}{ext}"))

    state["gate1_approved"] = False
    state["gate1_status"] = "changes_requested"
    state["gate1_feedback"] = feedback
    state["gate1_feedback_timestamp"] = now_iso
    state["gate1_feedback_qid"] = qid
    save_json(state_file, state)

    job = office_jobs.start(session_id, "pm")
    return {
        "session_id": session_id,
        "status": "changes_requested",
        "routed_qid": qid,
        "previous_version": f"docs/prd.v{version}.md",
        "message": f"Recorded as {qid}. The PM is rewriting the PRD from the updated discovery; "
                   f"the previous version is kept as docs/prd.v{version}.md.",
        "feedback": feedback,
        "job": job,
        "timestamp": now_iso,
    }


@architect_router.post("/architect/start")
def start_architect_endpoint(req: ArchitectSessionRequest):
    """
    Stage 3 Step 11: Real LLM Architect generates architecture.md, ADRs, openapi.yaml,
    schema.md, and team-plan.json. Validated by code before Tech Lead and Judge review.
    """
    session_id = req.session_id
    from main import get_session_dir, load_json, save_json
    from judge import evaluate_architecture_with_judge

    session_dir = get_session_dir(session_id)
    docs_dir = os.path.join(session_dir, "docs")
    adr_dir = os.path.join(docs_dir, "adr")
    os.makedirs(docs_dir, exist_ok=True)
    os.makedirs(adr_dir, exist_ok=True)

    prd_path = os.path.join(docs_dir, "prd.md")
    intake_path = os.path.join(session_dir, "intake.json")
    qa_path = os.path.join(session_dir, "qa_log.json")
    state_file = os.path.join(session_dir, "session_state.json")

    state = load_json(state_file, {})
    if not state.get("gate1_approved", False):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Cannot start Solution Architect: Gate 1 client approval is required before Stage 3 design."
        )

    with open(prd_path, "r", encoding="utf-8") as f:
        prd_text = f.read()

    prd_data = parse_prd_data(prd_text)
    intake_data = load_json(intake_path, {})
    qa_log = load_json(qa_path, [])
    parsed_ba = parse_ba_data(intake_data, qa_log, prd_text, session_id=session_id)

    # Stage 3 Step 11: LLM generates ADRs, Schema, OpenAPI, Team plan, Architecture TRD
    adrs = generate_adrs(parsed_ba, prd_data, adr_dir, session_id=session_id)
    schema_path = generate_schema_doc(parsed_ba, prd_data, docs_dir, session_id=session_id)
    openapi_path = generate_openapi_spec(parsed_ba, prd_data, docs_dir, session_id=session_id)
    team_plan_path = generate_team_plan(parsed_ba, prd_data, docs_dir, adrs=adrs)
    with open(schema_path, "r", encoding="utf-8") as f:
        schema_text = f.read()

    # Produce loop (Handbook 32): validate -> Judge -> findings back to the parts that hold them (max 2 rebuilds).
    trd_state: Dict[str, Any] = {}
    part_feedback: Dict[int, List[str]] = {}
    judge_rounds: List[Dict[str, Any]] = []
    # A rebuild can score lower than the round before it; the best round's documents are the ones kept.
    best: Optional[Tuple[Dict[str, Any], Dict[str, str], int]] = None
    for judge_round in range(1, 4):
        try:
            arch_path = generate_architecture_trd(parsed_ba, prd_data, docs_dir, adr_list=adrs, session_id=session_id,
                                                  state=trd_state, part_feedback=part_feedback)
        except ValueError:
            if best is None:
                raise
            logger.warning(f"Architecture Judge round {judge_round}: rebuild failed validation; keeping the best round")
            break
        with open(arch_path, "r", encoding="utf-8") as f:
            arch_text = f.read()
        # Stage 3 Step 13: Judge evaluation
        judge_verdict = evaluate_architecture_with_judge(
            arch_text=arch_text,
            prd_text=prd_text,
            parsed_ba=parsed_ba,
            rubric_path="skills/architect/rubric.json",
            session_id=session_id,
            schema_text=schema_text
        )
        judge_rounds.append({"round": judge_round, "pass": judge_verdict.get("pass"), "total": judge_verdict.get("total"),
                             "unsupported": len(judge_verdict.get("unsupported_claims") or [])})
        logger.info(f"Architecture Judge round {judge_round}: {judge_verdict.get('total')}/{judge_verdict.get('max')}, "
                    + ", ".join(f"{sc.get('criterion')} {sc.get('score')}/{sc.get('max')}" for sc in judge_verdict.get("scores") or []
                                if isinstance(sc, dict))
                    + f"; {len(judge_verdict.get('unsupported_claims') or [])} unsupported claims")
        if best is None or _verdict_rank(judge_verdict) > _verdict_rank(best[0]):
            best = (judge_verdict, _snapshot_docs(docs_dir), judge_round)
        if judge_verdict.get("pass") or judge_verdict.get("is_degraded") or judge_round == 3:
            break
        try:
            part_feedback, revised = revise_from_findings(judge_verdict, arch_text, parsed_ba, prd_data, docs_dir,
                                                          session_id, f"Architecture Judge round {judge_round}")
        except ValueError as e:
            logger.warning(f"Architecture Judge round {judge_round}: revision failed ({e}); keeping the best round")
            break
        adrs = revised or adrs
        if not part_feedback:
            break
        logger.info(f"Architecture Judge round {judge_round} failed; rebuilding parts {sorted(part_feedback)}")
    # Revisions after the best round (including a failed one) are undone, so the documents match the verdict.
    if best is not None and _snapshot_docs(docs_dir) != best[1]:
        logger.info(f"Keeping round {best[2]}'s documents: it scored {best[0].get('total')}, the last round "
                    f"{judge_verdict.get('total')}")
        _restore_docs(docs_dir, best[1])
        judge_verdict = best[0]
    judge_verdict["judge_rounds"] = judge_rounds

    architect_state = {
        "session_id": session_id,
        "status": "done" if judge_verdict.get("pass", False) else "review_failed",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "artifacts": {
            "architecture": "docs/architecture.md",
            "openapi": "docs/openapi.yaml",
            "schema": "docs/schema.md",
            "team_plan": "docs/team-plan.json",
            "adrs": [a["path"] for a in adrs]
        },
        "judge_verdict": judge_verdict
    }
    save_json(os.path.join(session_dir, "architect_state.json"), architect_state)

    return {
        "session_id": session_id,
        "status": architect_state["status"],
        "artifacts": architect_state["artifacts"],
        "judge_verdict": judge_verdict
    }


